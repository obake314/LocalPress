/**
 * 調達区分（工事 / 役務 / 物品）の判定と、使い物になる案件かどうかの選別。
 *
 * kkj API の Category は 45% が空で返る。区分で絞ると半分近くを捨てることに
 * なるため、題名と本文から補う。
 *
 * 区分コードは 1=物品 2=工事 3=役務（API の Category パラメータで確認）。
 */

/** 区分コード ↔ 名称 */
export const CATEGORY_CODE = { 物品: "1", 工事: "2", 役務: "3" }

/**
 * 題名が案件名として成立していない record を弾く。
 *
 * 発注元によっては ProjectName が PDF のファイル名や、
 * 表の断片（「６」「電気A・B級」など）のまま入っている。
 * 大槌町・八幡平市で多く見られた。掲載しても読み手に伝わらない。
 */
/**
 * そもそも調達案件ではない record を弾く。
 *
 * kkj は発注元が載せた PDF・Excel を1件ずつ拾うため、様式・契約書案・
 * 申請書・結果一覧といった「案件に付随する書類」が案件として混ざる。
 * 掲載しても応募できるものではない。
 */
const NOT_A_PROJECT = new RegExp(
  [
    "別記様式", "様式集", "様式[0-9０-９]", "各種様式",
    "契約書[（(]案[）)]", "契約約款",
    "落札者決定基準", "評価基準[（(]",
    "入札公告共通事項", "共通仕様書",
    "入札結果一覧", "結果一覧",
    "入札参加資格確認申請書", "参加表明書[（(]",
    "記載例", "記入例", "チェックリスト",
    "^[（(]別添", "^別添",
  ].join("|")
)

export function isProcurement(title) {
  return !NOT_A_PROJECT.test((title ?? "").trim())
}

export function isUsableTitle(title) {
  const t = (title ?? "").trim()
  if (t.length < 6) return false
  if (/\.(pdf|docx?|xlsx?|zip)$/i.test(t)) return false
  // 記号と数字だけ、あるいは伏字だらけのもの
  if (!/[ぁ-んァ-ヶ一-龥]/.test(t)) return false
  if ((t.match(/[_＿]/g) ?? []).length >= 4) return false
  return true
}

/**
 * 区分の判定。具体的な語から先に見る。
 *
 * 「〇〇工事」で終わるものは工事、物を買う・借りる語があれば物品、
 * 業務・委託・点検などがあれば役務。どれにも当たらなければ null を返す。
 */
const RULES = [
  // 工事に付随する設計・監理・調査は役務。題名に「工事」が入るため
  // 工事の規則より先に見ないと取り違える
  ["役務", /(設計|監理|管理|調査|補償|工損)[^。]{0,8}業務|業務委託/],
  // 工事。末尾が「工事」か、工種そのものを指す語
  ["工事", /工事(?!請負契約に係る入札参加資格)|舗装|除却|解体撤去|新築|増築|改築|土木一式|建築一式|造成|護岸|橋梁|下水道管渠/],
  // 物品。買う・借りる・納める対象
  ["物品", /購入|買入|賃貸借|借上|リース|売払|公売|供給|納入|調達（物品）|車両|自動車|乗用車|除雪車|ホイールローダ|パソコン|端末|備品|消耗品|燃料|印刷物|機器|部材|チェーン|フェンス|ポンプ|計[　 ]*一式|一式$/],
  // 役務。人が動く仕事
  ["役務", /業務|委託|点検|調査|監査|保守|管理|運営|清掃|警備|印刷|研修|講座|支援|派遣|作業|検査|測量|設計|運搬|輸送|保守|保険|プロポーザル/],
  // 上記で決まらない林業の請負は役務として扱う（造林・除伐・地拵など）
  ["役務", /造林|除伐|間伐|地拵|植付|下刈/],
]

/**
 * 工事に付随する設計・監理・調査などの業務。
 * 題名に「工事」が入るため、発注元自身が区分を「工事」にしていることがある。
 * 実態は役務なので、API の区分より題名を優先する。
 */
const KOJI_BUT_SERVICE = /(設計|監理|管理|調査|補償|工損)[^。]{0,8}業務|業務委託|システム[^。]{0,6}業務/

export function classifyCategory(item) {
  const given = (item.category ?? "").trim()
  const title = item.title ?? ""

  if (given === "工事" && KOJI_BUT_SERVICE.test(title)) return "役務"
  if (given) return given
  for (const [name, re] of RULES) if (re.test(title)) return name

  // 題名で決まらなければ本文の冒頭だけ見る（全文だと関係語を拾いすぎる）
  const head = (item.description ?? "").slice(0, 400)
  for (const [name, re] of RULES) if (re.test(head)) return name

  // 工事・役務・物品のどれとも言い切れないものは「その他」として残す。
  // 判定できないことを理由に落とすと、取りこぼしのほうが大きい
  return "その他"
}
